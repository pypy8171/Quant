import re

# "[Engine] 잔고 대조: 당일손익 -12345원 (총평가 123456)" — 제어 스레드 폴링마다 한 줄.
_PNL_HEAD = r"(?:잔고 대조|리컨사일): 당일손익"
PNL_RE = re.compile(_PNL_HEAD + r" (-?\d+)원 \(총평가 (\d+)\)")
PNL_ONLY_RE = re.compile(_PNL_HEAD + r" (-?\d+)원")

# "[Engine] 당일손익(전일대비): 322554원 (전일총자산 100218598)" — 전일 종가 대비.
#  위 잔고 대조 줄은 그 세션이 뜬 시점의 총평가를 0으로 잡으므로 재기동마다 기준이 옮겨가고,
#  간밤 갭도 빠진다. 하루의 성과는 이 줄로 읽어야 한다(2026-09-10에 부호까지 갈렸다).
PREV_PNL_RE = re.compile(r"당일손익\(전일대비\): (-?\d+)원 \(전일총자산 (\d+)\)")

# "[Main] manage_holdings: 청산 관리 N종목 부착, 스캔중복 M종목 스킵" — 기동 시 보유분 부착.
GUARD_ATTACH_RE = re.compile(r"청산 (?:관리|가디언) (\d+)종목 부착")
